"""Cisco Catalyst 8000v in controller (SD-WAN) mode: ``ciscosdwan_cloud_init.cfg``.

A text that is already a MIME bootstrap (as generated by SD-WAN Manager) is used
unchanged. Anything else is taken as the device's SD-WAN CLI configuration and
wrapped in a multipart cloud-config: the ``vinitparam`` values (uuid, otp,
vbond, org) are filled from the ``system`` section when present and otherwise
get lab placeholders, and the CLI text rides in a ``cloud-boothook`` part. The
bootstrap replaces the guest's accounts, so text without a ``username`` line is
refused: it would leave nobody able to log in.
"""

import hashlib
import json
import re

from gns3server.services.configurations.shared.errors import ConfigurationError

from ..media_profile import BootMediaProfile, MediaContext, checked_text, cli_text

TARGET = "ciscosdwan_cloud_init.cfg"
# Lab placeholders when the configuration names no controller. Manager
# registration always needs a Manager-generated bootstrap instead.
DEFAULT_VBOND = "0.0.0.0"
DEFAULT_ORG = "gns3-lab"
DEFAULT_OTP = "0" * 32


def is_bootstrap(text):
    return re.search(r"^MIME-Version:", text, re.I | re.M) is not None


def has_login(text):
    return re.search(r"^username[ \t]+\S", text, re.M) is not None


def system_value(text, keyword):
    """Value of the first ``keyword value`` line of the ``system`` section, or None.

    The value is the first word, or a double-quoted string as the CLI prints it
    (``vbond 10.0.0.1 port 12346`` gives ``10.0.0.1``). The quoting is the
    device's, not JSON: anything up to the closing quote is taken verbatim.
    """
    section = re.search(r"^system[ \t]*\r?\n((?:[ \t]+[^\n]*\n?|!\r?\n?)*)", text, re.M)
    match = re.search(rf'^[ \t]+{keyword}[ \t]+(?:"([^"\n]*)"|([^\s"]+))', section[1], re.M) if section else None
    if match is None:
        return None
    return match[1] if match[1] is not None else match[2]


def wrap(text, node_id):
    vbond = system_value(text, "vbond") or DEFAULT_VBOND
    org = system_value(text, "organization-name") or DEFAULT_ORG
    cloud = (
        "#cloud-config\nvinitparam:\n"
        f" - uuid : C8K-{node_id}\n"
        f' - otp : "{DEFAULT_OTP}"\n'
        f" - vbond : {json.dumps(vbond)}\n"
        f" - org : {json.dumps(org)}\n"
        " - rcc : true\nca-certs:\n remove-defaults: false\n"
    )
    # A reproducible boundary that occurs in neither payload.
    boundary = "gns3-" + hashlib.sha256((text + node_id).encode()).hexdigest()
    while boundary in text:
        boundary += "x"
    parts = []
    for name, mime, body in (
        ("cloud-config", "text/cloud-config", cloud),
        ("config.txt", "text/cloud-boothook", "#cloud-boothook\n" + text),
    ):
        parts.append(
            f"--{boundary}\nContent-Type: {mime}; charset=utf-8\n"
            f'Content-Disposition: attachment; filename="{name}"\n'
            f"Content-Transfer-Encoding: 8bit\n\n{body}\n"
        )
    head = f'Content-Type: multipart/mixed; boundary="{boundary}"\nMIME-Version: 1.0\n\n'
    return head + "".join(parts) + f"--{boundary}--\n"


def render(content, context: MediaContext):
    # A Manager bootstrap is delivered byte for byte; plain CLI text is parsed, so it gets LF endings.
    text = checked_text(content)
    if is_bootstrap(text):
        return {TARGET: text.encode("utf-8")}
    text = cli_text(text)
    if not has_login(text):
        raise ConfigurationError("configuration_login_required")
    return {TARGET: wrap(text, context.node_id).encode("utf-8")}


PROFILE = BootMediaProfile(
    id="cisco-c8000v-controller",
    title="Cisco C8000v controller",
    description="Delivers ciscosdwan_cloud_init.cfg on a CD-ROM; plain SD-WAN CLI text is wrapped in a bootstrap.",
    device_types=("cisco_ios_telnet",),
    volume_label="CONFIG",
    render=render,
)
